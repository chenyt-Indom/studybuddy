MEMORY_EXTRACT_PROMPT = """你是学习档案记录员。从下面这段师生对话中，提取关于「这名学生」的长期有用信息。

【对话】
{conversation}

【分两层，用 scope 区分】
- scope = "global"：跨学科的、关于**这个人本身**的长期特征
  身份与学段、学习目标、时间与作息习惯、认知偏好、情绪基调、生活/家庭约束
- scope = "subject"：只跟**当前这个学科**有关的记忆
  某知识点的薄弱或误区、易错题型、对某类讲法的接受度

【每条的硬要求】
1. content：一句话（不超过 40 字），是「可复用的判断」，不是「对话摘要」
2. evidence：从对话里摘 10~40 字**原话**作为依据，用于事后核查。不许自己编
3. confidence：你对这条判断的把握，0~1。拿不准就给 0.4 以下
4. type 只能取：identity / goal / habit / preference / emotion / weakness / misconception

【不要提取】
- 题目本身的内容、你已经讲过的知识点
- 一次性的临时状态（比如「这道题不会」）
- 任何你只是猜测、对话里没有依据的东西

【没有值得记的就返回空数组，不要凑数】

【输出】严格 JSON 数组，不要任何解释文字：
[{{"scope":"global","type":"goal","content":"目标报考人工智能技术应用专业","evidence":"我想报人工智能技术应用","keywords":"目标,专业","confidence":0.9}}]
"""

